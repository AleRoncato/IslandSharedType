use crate::types::{Clue, Params, Round, Seed, ShipId};
use std::fmt::{Display, Formatter};

/// Result of a Ship's `AskClue` action, as decided by the Island.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IslandResponse {
    /// pass an instance of the island's clue weakened or full.
    Respond(Clue),
    /// The island refused to give the clue to the requesting ship due to the island's policies.
    Refused,
    /// The requesting ship has to wait at least n rounds before receiving a version of the clue.
    Wait(u32),
    /// The requesting ship has already received the full strength clue.
    NothingMore,
}

/// island's response to a moor request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MoorResponse {
    /// The island approved the ship's mooring request.
    Accepted,
    /// The island rejects the request due to its policies.
    Refused,
    /// The island rejects the request due to full berth.
    NoBerth,
}

/// How an Island answers to a repair_hull request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RepairHullResponse {
    /// the island repairs the requesting ship's hull by 'h' hulls. To be discussed of whose responsibility is to check if old_hull + h > hull_max
    Accepted(u32),
    /// request rejected due to island own policies.
    Refused,
    /// (n > 0) The ships has to wait at least n rounds to be repaired.
    Wait(u32),
}

/// Readable display intended primarily for debugging and examples.
impl Display for IslandResponse{
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        match self{
            IslandResponse::Respond(clue) => write!(f,"Response with clue: {:?}", clue),
            IslandResponse::Wait(round) => write!(f,"Must wait {:?} rounds", round),
            IslandResponse::Refused => write!(f,"Refused"),
            IslandResponse::NothingMore => write!(f,"Nothing More"),
        }
    }
}

/// Readable display intended primarily for debugging and examples.
impl Display for MoorResponse{
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        match self{
            MoorResponse::Accepted => write!(f,"Accepted"),
            MoorResponse::NoBerth => write!(f,"NoSpace"),
            MoorResponse::Refused => write!(f,"Refused"),
        }
    }
}

/// Data supplied by the Chart when constructing a concrete Island.
///
/// The Chart determines the original Clue and provides a reproducible source
/// of Island randomness. A concrete Island is responsible for initializing its
/// own internal state from these inputs.
///
/// TODO: Confirm seed derivation/independence across Islands and how the Chart selects concrete Island implementations at construction time.
#[derive(Debug, Clone, Copy)] //Struct in cui riceve da Chart tutte cose
pub struct IslandInit{
    /// The Island's original true Clue, generated by the Chart.
    pub clue: Clue,
    /// Deterministic seed supplied by the Chart for the Island's PRNG.
    pub seed: Seed,
    /// Game configuration; the same configuration used to generate the world.
    pub params: Params,
}

pub trait Island {

    /// Each concrete Island implementation is responsible for initializing its internal state and deciding how to use these values.
    ///
    /// This method is called once per Island during world initialization.
    ///
    /// # Note
    /// This method requires `Self: Sized` because it constructs a concrete Island type and cannot be called through a `dyn Island` trait object.
    fn new(init: IslandInit) -> Self where Self: Sized;

    /// **applies** a valid moor request
    ///The chart calls this method to **apply** the moor request from Ship S to the Island I.
    ///
    /// The Chart calls this only after checking all applicable game rules, including [`Island::can_moor`], and immediately applying that validated action.
    ///
    /// moor method mutates the island's state
    fn moor(&mut self, ship: ShipId);

    /// Checks whether `ship` would be accepted for mooring *without mutation*.
    /// this method is called by the Chart during the moor request's validation process.
    ///
    /// the method only checks the request against the island's policies and berth capacity; it does not check geometry constraints and other game rules.
    ///
    /// Repeated calls against unchanged state must not have side effects, including consuming the Island's stateful PRNG.
    ///
    /// The returned [`MoorResponse`] describes this check; it does not record that the Ship has actually moored.
    fn can_moor(&self, ship: ShipId) -> MoorResponse; // read-only method

    /// Reports whether `ship` is currently registered as moored at this Island.
    ///
    /// This is a read-only query. If both the Chart and Island keep mooring information, their answers must stay consistent.
    ///
    /// WG TODO: The Chart already knows each Ship's mooring state; decide whether this query is necessary/useful in the trait.
    fn is_moored(&self, ship: ShipId) -> bool;

    /// makes a moored ship leave the berth
    /// this method is called by the chart **after** validating that the ship is actually moored.
    /// WG TODO: Define any additional call sites, e.g. a Ship sinking while moored, and the effect of departure on partial waiting progress.
    fn leave_berth(&mut self, ship: ShipId);

    /// Creates an [`IslandResponse`] for `ship` according to the Island policies.
    ///
    /// The Chart must call this method after validating and checking whether `ship` is moored to Island.
    fn ask_clue(&mut self, ship: ShipId) -> IslandResponse;

    /// Returns the number of rounds `ship` must still wait under the Island's current clue-delivery policy.
    ///
    /// - `Some(n)` indicates that `n` additional rounds of waiting are required.
    /// - `Some(0)` indicates that no further waiting is required under the current arrangement.
    /// - `None` indicates that no waiting period is currently defined for the requesting Ship.
    ///
    /// This method must not modify the Island's state.
    ///
    /// WG TODO: Confirm the exact conditions under which `None` is returned, particularly for non-moored Ships and Ships that already possess the full-strength Clue.
    fn remaining_wait(&self, ship: ShipId) -> Option<u32>;

    /// Indicates whether the Island has a Clue improvement left for `ship`.
    ///
    /// This must be `false` once the Ship has received this Island's original, full-strength Clue. Receiving only a weakened Clue does not, by itself, exhaust the Island's offer to that Ship.
    ///
    /// Read-only method.
    fn has_more_to_offer(&self, ship: ShipId) -> bool;

    /// Notifies the Island that the Chart has advanced to `round`.
    ///
    /// The Chart increments the global round first, then calls this method exactly once per Island
    ///
    /// The Island must not independently increment the *global* round.
    fn round_advance(&mut self, round: Round);

    //Optional and TBD

    /// Queries this Island's optional hull-repair service for `ship`.
    ///
    /// The Chart owns Ship hull points and applies any accepted repair, never allowing the hull to exceed `Params::hull_strength`.
    ///
    /// WG TODO: Define when this method may be called, whether its response is a quote or the actual repair decision, and whether `&mut self` is required.
    fn repair_hull(&self, ship: ShipId) -> RepairHullResponse;

    /// Returns historical visit information that this Island chooses to disclose to the requesting Ship.
    ///
    /// The Island is free to maintain its internal history using any data structure. It is not required to store or reveal every visit.
    ///
    /// - `None` indicates that no history response is available.
    /// - `Some(records)` contains the visit records disclosed to the requester. An empty vector is a valid response.
    ///
    /// The `requester` parameter identifies the Ship requesting the information, not the Ships described by the records.
    ///
    /// This method must not modify the Island's state.
    ///
    /// This method is Default None since its optional
    ///
    /// WG TODO: Define how the Chart triggers this optional service and communicates its result to the requesting Ship, since AskHistory is not a Main 5.3 action.
    fn ask_history(&self, requester: ShipId, ) -> Option<Vec<VisitRecord>> { None }
}

/// Represents a single visit made by a Ship to an Island.
///
/// A Ship may visit the same Island multiple times.
/// Each visit is represented by a separate `VisitRecord`.
///
/// The visit starts at `arrival_round` and ends at `departure_round`, if the Ship has left.
///
/// An absent departure round (None) indicates an ongoing visit.
///
/// Island implementations are free to use any internal data structure to track their history.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VisitRecord {
    /// Identifier of the visiting Ship.
    pub ship: ShipId,

    /// Round in which the Ship moored at this Island.
    pub arrival_round: Round,

    /// Round in which the Ship left the Island.
    /// `None` indicates that the Ship is still moored.
    pub departure_round: Option<Round>,
}